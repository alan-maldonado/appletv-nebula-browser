+ (NSString *)HTMLWithAccentHex:(NSString *)accentHex onAccentHex:(NSString *)onAccentHex {
    // Favicon: the same mark on an indigo tile so it reads on light tab bars too.
    NSString *favicon = [kBrowserRemoteLogoSVG stringByReplacingOccurrencesOfString:@" class='logo'" withString:@""];
    favicon = [favicon stringByReplacingOccurrencesOfString:@" aria-hidden='true'>" withString:@"><rect width='64' height='64' rx='14' fill='#2E2160'/>"];
    favicon = [favicon stringByReplacingOccurrencesOfString:@"<svg " withString:@"<svg xmlns='http://www.w3.org/2000/svg' "];
    favicon = [favicon stringByAddingPercentEncodingWithAllowedCharacters:NSCharacterSet.URLQueryAllowedCharacterSet];
    favicon = [favicon stringByReplacingOccurrencesOfString:@"#" withString:@"%23"];

    NSString *HTML = [kBrowserRemotePageTemplate stringByReplacingOccurrencesOfString:@"__LOGO__" withString:kBrowserRemoteLogoSVG];
    HTML = [HTML stringByReplacingOccurrencesOfString:@"__FAVICON__" withString:favicon];
    HTML = [HTML stringByReplacingOccurrencesOfString:@"__ON_ACCENT__" withString:onAccentHex];
    return [HTML stringByReplacingOccurrencesOfString:@"__ACCENT__" withString:accentHex];
}

